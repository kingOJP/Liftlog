// Catalog + taxonomy + exercise metadata (exercises.ts, taxonomy.ts).
// Also generates ios/LiftLogCore/Sources/LiftLogCore/Generated/CatalogData.swift
// from the exported TS tables, so the catalog has ONE source of truth (CI fails
// if the committed Swift copy drifts).
import { it } from 'vitest';
import { writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { Fixture } from '../harness';
import {
  EXERCISES, DIFFICULTY, PREREQUISITES, MUSCLE_HEADS, PRIMARY_HEADS, catalogDefFor, difficultyFor,
  hasCatalogDifficulty, unitFor, isTimedExercise, prerequisitesFor, headsFor, getExerciseMeta,
  saveExerciseMeta, deleteExerciseMeta, getAllExerciseMeta, mergeExerciseMeta,
} from '../../../src/data/exercises';
import type { ExerciseMetaOverride } from '../../../src/data/exercises';
import { regionFor, patternCategoryFor, unitLabel, MUSCLE_GROUPS, MOVEMENT_PATTERNS } from '../../../src/data/taxonomy';

const q = (s: string | null | undefined): string => (s == null ? 'nil' : JSON.stringify(s));
const enumCase = (raw: string | null | undefined): string => (raw == null ? 'nil' : `.init(rawValue: ${JSON.stringify(raw)})!`);

function generateSwift(): string {
  const lines: string[] = [
    '// GENERATED by ios/parity/cases/catalog.parity.ts from src/data/exercises.ts — do not edit.',
    '// Regenerate with `npm run parity:fixtures`.',
    '// swiftlint:disable all',
    '',
    'enum CatalogData {',
    '    static let exercises: [ExerciseDef] = [',
  ];
  for (const e of EXERCISES) {
    const sec = e.secondaryMuscles.map(enumCase).join(', ');
    lines.push(`        ExerciseDef(id: ${q(e.id)}, name: ${q(e.name)}, primaryMuscle: ${enumCase(e.primaryMuscle)}, secondaryMuscles: [${sec}], workoutType: ${enumCase(e.workoutType)}, equipment: ${enumCase(e.equipment)}, weightType: ${enumCase(e.weightType)}, unit: ${enumCase(e.unit)}),`);
  }
  lines.push('    ]', '');
  lines.push('    static let difficulty: [String: ExerciseDifficulty] = [');
  for (const [k, v] of Object.entries(DIFFICULTY)) lines.push(`        ${q(k)}: .${v},`);
  lines.push('    ]', '');
  lines.push('    static let prerequisites: [String: [String]] = [');
  for (const [k, v] of Object.entries(PREREQUISITES)) lines.push(`        ${q(k)}: [${v.map(q).join(', ')}],`);
  lines.push('    ]', '');
  lines.push('    static let muscleHeads: [MuscleGroup: [String]] = [');
  for (const [k, v] of Object.entries(MUSCLE_HEADS)) lines.push(`        ${enumCase(k)}: [${(v ?? []).map(q).join(', ')}],`);
  lines.push('    ]', '');
  lines.push('    static let primaryHeads: [String: [String]] = [');
  for (const [k, v] of Object.entries(PRIMARY_HEADS)) lines.push(`        ${q(k)}: [${v.map(q).join(', ')}],`);
  lines.push('    ]', '}', '');
  return lines.join('\n');
}

const SAMPLE_IDS = [...new Set([
  'bench-press', 'squat', 'plank', 'side-plank', 'pull-ups', 'romanian-deadlifts', 'conventional-deadlift',
  'back-extensions-1782325116469', 'custom-landmine-1700000000000', 'not-a-real-id', 'barbell-row-12',
  ...EXERCISES.map(e => e.id),
])];

const legacyMeta: Record<string, unknown> = {
  'bench-press': { primaryMuscle: 'Chest', secondaryMuscle1: 'Front Delts', secondaryMuscle2: 'Triceps', secondaryMuscle3: 'Chest', workoutType: 'Press', equipment: 'Bench', weightType: 'Barbell', updatedAt: 5 },
  'custom-overhead-thing': { primaryMuscle: 'Side Delts', secondaryMuscle1: 'Rear Delts', secondaryMuscle2: null, secondaryMuscle3: null, workoutType: 'Press', equipment: 'Leg Press Machine', weightType: 'Machine' },
  'custom-push': { primaryMuscle: 'Chest', secondaryMuscle1: null, secondaryMuscle2: null, secondaryMuscle3: null, workoutType: 'Push Up', equipment: null, weightType: 'Bodyweight' },
  'custom-ohp': { primaryMuscle: 'Delts', secondaryMuscle1: 'Triceps', secondaryMuscle2: 'Delts', secondaryMuscle3: null, workoutType: 'Overhead Press', equipment: null, weightType: 'Dumbbell' },
};
const globalMeta: Record<string, ExerciseMetaOverride> = {
  squat: { primaryMuscle: 'Quads', secondaryMuscle1: 'Glutes', secondaryMuscle2: null, secondaryMuscle3: null, workoutType: 'Squat', equipment: 'Squat Rack', weightType: 'Barbell' },
  'custom-global': { primaryMuscle: 'Lats', secondaryMuscle1: null, secondaryMuscle2: null, secondaryMuscle3: null, workoutType: 'Pull Down', equipment: 'Cable Machine', weightType: 'Machine' },
};

it('catalog fixture', () => {
  const dir = join(__dirname, '../../LiftLogCore/Sources/LiftLogCore/Generated');
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'CatalogData.swift'), generateSwift());

  const f = new Fixture('catalog');
  f.record('catalog size', 'catalogIds', [], () => EXERCISES.map(e => e.id));
  for (const id of SAMPLE_IDS) {
    f.record(`lookup ${id}`, 'lookup', [id], (x: string) => ({
      def: catalogDefFor(x), difficulty: difficultyFor(x), hasDifficulty: hasCatalogDifficulty(x), unit: unitFor(x),
      timed: isTimedExercise(x), prereqs: prerequisitesFor(x), heads: headsFor(x), meta: getExerciseMeta(x),
    }));
  }
  for (const m of MUSCLE_GROUPS) f.record(`region ${m}`, 'regionFor', [m], regionFor);
  for (const p of MOVEMENT_PATTERNS) f.record(`category ${p}`, 'patternCategoryFor', [p], patternCategoryFor);
  f.record('unitLabel', 'unitLabels', [], () => [unitLabel('reps'), unitLabel('reps', false), unitLabel('seconds'), unitLabel('seconds', false)]);

  const storage = { liftlog_exercise_meta: legacyMeta, liftlog_global_meta: globalMeta };
  for (const id of ['bench-press', 'custom-overhead-thing', 'custom-push', 'custom-ohp', 'squat', 'custom-global', 'deadlift', 'custom-none']) {
    f.record(`meta layered ${id}`, 'getExerciseMeta', [id], getExerciseMeta, { storage });
  }
  f.record('meta all (normalized)', 'getAllExerciseMeta', [], getAllExerciseMeta, { storage });
  f.record('meta corrupt json', 'getAllExerciseMeta', [], getAllExerciseMeta, { storage: { liftlog_exercise_meta: '{not json' } });
  f.record('save meta', 'saveExerciseMeta', ['custom-push', globalMeta.squat, 99], (id: string, m: ExerciseMetaOverride, now: number) => {
    saveExerciseMeta(id, m, now); return getAllExerciseMeta();
  }, { storage });
  f.record('delete meta', 'deleteExerciseMeta', ['bench-press'], (id: string) => { deleteExerciseMeta(id); return getAllExerciseMeta(); }, { storage });
  const incoming: Record<string, ExerciseMetaOverride> = {
    'bench-press': { ...globalMeta.squat, updatedAt: 4 },      // older than local (5) → local kept
    'custom-push': { ...globalMeta.squat, updatedAt: 1 },      // local unstamped → incoming wins
    'brand-new': { ...globalMeta['custom-global'] },
  };
  f.record('merge meta', 'mergeExerciseMeta', [incoming], (inc: Record<string, ExerciseMetaOverride>) => { mergeExerciseMeta(inc); return getAllExerciseMeta(); }, { storage });
  f.write();
});
