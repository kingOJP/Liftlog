/// <reference types="vitest/config" />
import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'
import { VitePWA } from 'vite-plugin-pwa'
import { execSync } from 'node:child_process'
import { readFileSync } from 'node:fs'

// Stamped into the bundle (src/data/appInfo.ts) so Settings, the support page
// and crash reports can name the exact build. The commit comes from the CI
// environment when there is one, from git otherwise.
const pkg = JSON.parse(readFileSync(new URL('./package.json', import.meta.url), 'utf8')) as { version: string }
function buildId(): string {
  const fromEnv = process.env.WORKERS_CI_COMMIT_SHA ?? process.env.CF_PAGES_COMMIT_SHA ?? process.env.GITHUB_SHA
  if (fromEnv) return fromEnv.slice(0, 7)
  try { return execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim() } catch { return 'local' }
}

// iOS shows a launch image only when one matches the device exactly; these are
// the logical sizes (CSS px @ device pixel ratio) of every iPhone still on a
// supported iOS. The images are generated by scripts/generate-pwa-assets.mjs.
const IOS_SPLASH: Array<[number, number, number]> = [
  [320, 568, 2], [375, 667, 2], [414, 736, 3], [375, 812, 3], [414, 896, 2], [414, 896, 3],
  [390, 844, 3], [428, 926, 3], [393, 852, 3], [430, 932, 3], [402, 874, 3], [440, 956, 3],
]

export default defineConfig({
  define: {
    __APP_VERSION__: JSON.stringify(pkg.version),
    __BUILD_ID__: JSON.stringify(buildId()),
  },
  test: {
    // `node`, not `jsdom`: the data layer only needs localStorage, which
    // src/test/setup.ts provides. Files that need a real DOM opt in with a
    // `@vitest-environment jsdom` docblock. See src/test/setup.ts.
    environment: 'node',
    setupFiles: ['./src/test/setup.ts'],
    include: ['src/**/*.test.ts', 'worker/**/*.test.ts', 'test/**/*.test.ts'],
  },
  plugins: [
    react(),
    {
      // One <link> per device, written at build time rather than by hand.
      name: 'ios-launch-images',
      transformIndexHtml() {
        return IOS_SPLASH.map(([w, h, dpr]) => ({
          tag: 'link',
          injectTo: 'head' as const,
          attrs: {
            rel: 'apple-touch-startup-image',
            href: `/splash/launch-${w * dpr}x${h * dpr}.png`,
            media: `(device-width: ${w}px) and (device-height: ${h}px) and (-webkit-device-pixel-ratio: ${dpr}) and (orientation: portrait)`,
          },
        }))
      },
    },
    VitePWA({
      registerType: 'autoUpdate',
      manifest: {
        // A stable identity: without `id` the install is keyed on start_url,
        // and changing that later would orphan every installed copy.
        id: '/',
        name: 'LiftLog',
        short_name: 'LiftLog',
        description: 'A strength coach in your pocket: plan your training, log workouts, and get recommendations from your own history.',
        lang: 'en',
        dir: 'ltr',
        categories: ['health', 'fitness', 'sports'],
        // Both match --bg, so the launch screen, the status bar and the first
        // painted frame are the same colour (a purple bar used to flash first).
        theme_color: '#0a0a0f',
        background_color: '#0a0a0f',
        display: 'standalone',
        orientation: 'portrait',
        start_url: '/',
        scope: '/',
        icons: [
          { src: 'icons/icon-192x192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
          { src: 'icons/icon-512x512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
          // Maskable icons are cropped to a circle/squircle by the launcher, so
          // they are separate full-bleed files with the mark inside the safe zone.
          { src: 'icons/maskable-192x192.png', sizes: '192x192', type: 'image/png', purpose: 'maskable' },
          { src: 'icons/maskable-512x512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
        ],
      },
      workbox: {
        // Launch images and store artwork are fetched by the OS, not the app:
        // precaching them would add to every install for nothing.
        globPatterns: ['**/*.{js,css,html,svg,ico}'],
        globIgnores: ['**/store/**', '**/splash/**'],
        cleanupOutdatedCaches: true,
        navigateFallbackDenylist: [/^\/api\//],
      },
    }),
  ],
})
